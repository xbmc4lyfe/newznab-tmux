<?php

declare(strict_types=1);

/**
 * Regenerates docker/app/nzb-yenc-ffi/src/header_filename_unicode.rs from the PHP runtime's own
 * PCRE tables, so Rust's \p{L} and \p{N} agree with the preg lookarounds in HeaderFilenameIdentity.
 *
 *   php scripts/generate-header-filename-unicode.php > docker/app/nzb-yenc-ffi/src/header_filename_unicode.rs
 */
if (PHP_SAPI !== 'cli') {
    exit(1);
}

/** @return list<array{int,int}> */
function headerFilenameUnicodeRanges(string $pattern): array
{
    $ranges = [];
    $start = null;
    for ($code = 0; $code <= 0x110000; $code++) {
        $in = $code <= 0x10FFFF && ($code < 0xD800 || $code > 0xDFFF)
            && preg_match($pattern, mb_chr($code, 'UTF-8')) === 1;
        if ($in && $start === null) {
            $start = $code;
        } elseif (! $in && $start !== null) {
            $ranges[] = [$start, $code - 1];
            $start = null;
        }
    }

    return $ranges;
}

/** @param list<array{int,int}> $ranges */
function headerFilenameUnicodeRender(string $name, array $ranges): string
{
    $lines = [];
    foreach (array_chunk($ranges, 6) as $chunk) {
        $lines[] = '    '.implode(' ', array_map(static fn (array $r): string => sprintf('(0x%04X, 0x%04X),', $r[0], $r[1]), $chunk));
    }

    return sprintf("#[rustfmt::skip]\npub(crate) const %s: &[(u32, u32)] = &[\n%s\n];\n", $name, implode("\n", $lines));
}

echo "//! Generated by scripts/generate-header-filename-unicode.php; do not edit by hand.\n";
echo '//! PCRE2 '.PCRE_VERSION." general categories L, M and N, and the UCP-aware /u \\s and \\d classes, as used by\n";
echo "//! App\\Services\\Releases\\Verification\\HeaderFilenameIdentity (UTF mode).\n\n";
echo headerFilenameUnicodeRender('LETTERS', headerFilenameUnicodeRanges('/\A\p{L}\z/u'))."\n";
echo headerFilenameUnicodeRender('NUMBERS', headerFilenameUnicodeRanges('/\A\p{N}\z/u'))."\n";
echo headerFilenameUnicodeRender('MARKS', headerFilenameUnicodeRanges('/\A\p{M}\z/u'))."\n";
echo headerFilenameUnicodeRender('DIGITS', headerFilenameUnicodeRanges('/\A\d\z/u'))."\n";
echo headerFilenameUnicodeRender('SPACES', headerFilenameUnicodeRanges('/\A\s\z/u'));
